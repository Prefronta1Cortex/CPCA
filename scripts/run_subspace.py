"""Reading the order from the whole reduced space (docs/subspace.md), hc-11 only.

Per session and sleep epoch: centred complex PCA on all NREM population bursts; five read-outs (best
component, subspace seriation, subspace phase synchronisation, direction-blind seriation, count PCA
seriation), each scored against both running directions' place maps with the best-of-outputs null.

Usage: python scripts/run_subspace.py [--workers=10]
Results: results/subspace/<session>_<epoch>.pkl, results/subspace/summary.md
"""

import os
import pickle
import sys
import zlib
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "results" / "subspace"
HC11_ORDER = ["Achilles_10252013", "Achilles_11012013", "Buddy_06272013", "Cicero_09012014",
              "Cicero_09102014", "Cicero_09172014", "Gatsby_08022013", "Gatsby_08282013"]
READOUTS = [("component", "best component"), ("seriation", "subspace seriation"), ("phase_sync", "subspace phase synchronisation"),
            ("magnitude", "direction-blind seriation (control)"), ("count", "count PCA seriation (control)")]


def seed(*parts):
    return zlib.crc32("|".join(map(str, parts)).encode())


def job(name, epoch):
    from cpca import event_spike_times, fit, population_bursts
    from cpca.direction import order_of
    from cpca.hc11 import load_session, nrem_intervals, place_centres, pyramidal_spikes, running, session_paths
    from cpca.subspace import phase_sync, reduced_covariance, seriate
    from scripts.plot_hc11_sequences import best_map_match
    from scripts.run_topology import count_similarity
    session = load_session(next(p for p in session_paths() if p.name.startswith(name)))
    run = running(session)
    iv = nrem_intervals(session, epoch)
    by_cell, cell_ids, pooled = pyramidal_spikes(session, iv)
    bursts, peaks = population_bursts(pooled, iv)
    dur = np.diff(bursts, axis=1).ravel()
    times, _ = event_spike_times(by_cell, cell_ids, peaks - dur / 2, peaks + dur / 2)
    centres = place_centres(session, cell_ids, run)
    rng = np.random.default_rng(seed("subspace", name, epoch))
    res = fit(times, dur * 1000, rng=rng, ica=False)
    k = res["n_kept"]
    ring = run["circular"]
    orders = {}
    orders["component"] = [order_of(res["pca_components"][:, j]) for j in range(k)]
    if k:
        C = reduced_covariance(res["eigenvalues"], res["pca_components"], k)
        d = np.sqrt(np.clip(np.real(np.diag(C)), 1e-300, None))
        orders["seriation"] = [seriate(np.real(C) / np.outer(d, d), ring=ring)]
        orders["phase_sync"] = [phase_sync(C)]
        orders["magnitude"] = [seriate(np.abs(C) / np.outer(d, d), ring=ring)]
    else:
        orders["seriation"] = orders["phase_sync"] = orders["magnitude"] = []
    S_count, k_count = count_similarity(times, rng)
    orders["count"] = [seriate(S_count, ring=ring)] if k_count else []
    scores = {r: (best_map_match(o, centres, run["circular"], run["length"], rng) if o else {"abs": np.nan, "p": np.nan, "index": -1})
              for r, o in orders.items()}
    result = {"name": name, "epoch": epoch, "circular": ring, "k": k, "k_count": k_count, "n_events": len(peaks), "scores": scores,
              "orders": orders, "centres": centres}
    OUT.mkdir(parents=True, exist_ok=True)
    pickle.dump(result, open(OUT / f"{name}_{epoch}.pkl", "wb"))
    return name, epoch, {r: (round(s["abs"], 2) if np.isfinite(s["abs"]) else None, round(s["p"], 3) if np.isfinite(s["p"]) else None) for r, s in scores.items()}


def summary():
    R = {(r["name"], r["epoch"]): r for r in (pickle.load(open(p, "rb")) for p in sorted(OUT.glob("*.pkl")))}
    lines = ["# Reading the order from the whole reduced space: hc-11", "",
             "Generated by `scripts/run_subspace.py`. Design: `docs/subspace.md`. Cells: |ρ| of the read-out against the better of the two "
             "direction maps (either sense), p against the best-of-outputs null.", "",
             "| session | epoch | k | " + " | ".join(lab for _, lab in READOUTS) + " |", "|---" * (len(READOUTS) + 3) + "|"]
    for n in HC11_ORDER:
        for e in ("post", "pre"):
            r = R[(n, e)]
            cells = [f"{r['scores'][k]['abs']:.2f} (p {r['scores'][k]['p']:.3f})" if np.isfinite(r["scores"][k]["abs"]) else "–" for k, _ in READOUTS]
            lines.append(f"| {n} | {e.upper()} | {r['k']} | " + " | ".join(cells) + " |")
    for e in ("post", "pre"):
        lines.append(f"| **sessions with p < 0.05** | {e.upper()} | | " + " | ".join(
            f"{sum(np.isfinite(R[(n, e)]['scores'][k]['p']) and R[(n, e)]['scores'][k]['p'] < 0.05 for n in HC11_ORDER)}/8" for k, _ in READOUTS) + " |")
    (OUT / "summary.md").write_text("\n".join(lines) + "\n")
    return R


def figure(R):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    from scripts.summarize_topology import GRID, INK, POST_C, PRE_C, SOFT, short
    fig = plt.figure(figsize=(13.5, 6.2))
    ax = fig.add_axes([0.07, 0.15, 0.9, 0.58])
    fig.text(0.035, 0.94, "hc-11: one order from the whole reduced space is not better than the best single component", fontsize=15, fontweight="bold")
    fig.text(0.035, 0.895, "Each read-out gives the cells one order from the same centred complex PCA fit (count PCA: from spike counts),", fontsize=10.2, color=SOFT)
    fig.text(0.035, 0.862, "scored against both running directions' place maps in either sense; p against the best-of-outputs null.", fontsize=10.2, color=SOFT)
    rng = np.random.default_rng(0)
    for j, (key, label) in enumerate(READOUTS):
        for e, dx, col, face in (("post", -0.13, POST_C, POST_C), ("pre", 0.13, PRE_C, "white")):
            p = np.array([R[(n, e)]["scores"][key]["p"] for n in HC11_ORDER], float)
            y = -np.log10(np.where(np.isfinite(p), p, 1.0))
            ax.scatter(j + dx + rng.uniform(-0.05, 0.05, len(y)), y, s=34, facecolor=face, edgecolor=col, lw=1.3, zorder=3)
            k = int(np.sum(np.isfinite(p) & (p < 0.05)))
            ax.text(j + dx, 3.2, f"{k}/8", ha="center", fontsize=9.5, color=col, fontweight="bold" if e == "post" else "normal")
    ax.axhline(-np.log10(0.05), color=SOFT, lw=0.9, ls=(0, (3, 3)))
    ax.text(len(READOUTS) - 0.45, -np.log10(0.05) + 0.04, "p = 0.05", ha="right", va="bottom", fontsize=8.5, color=SOFT)
    ax.axvspan(2.5, 4.5, color=GRID, alpha=0.5, lw=0, zorder=0)
    ax.text(3.5, 2.95, "controls", ha="center", fontsize=9, color=SOFT, fontstyle="italic")
    ax.set_xticks(range(len(READOUTS)))
    ax.set_xticklabels([lab.replace(" (control)", "").replace("subspace ", "subspace\n").replace("count PCA ", "count PCA\n")
                        .replace("direction-blind ", "direction-blind\n").replace("best ", "best\n") for _, lab in READOUTS], fontsize=9.6)
    ax.tick_params(axis="x", length=0)
    ax.set_xlim(-0.6, len(READOUTS) - 0.4)
    ax.set_ylim(0, 3.45)
    ax.set_ylabel("read-out vs map, −log10 p (one dot per session)")
    ax.yaxis.grid(True, color=GRID)
    ax.set_axisbelow(True)
    ax.legend(handles=[Line2D([], [], marker="o", ls="", color=POST_C, ms=6, label="sleep after the maze (POST)"),
                       Line2D([], [], marker="o", ls="", mfc="white", mec=PRE_C, mew=1.3, ms=6, label="sleep before (PRE)")],
              loc="upper left", bbox_to_anchor=(0, 1.13), ncol=2, frameon=False, fontsize=9)
    ax.text(1.0, 1.08, "numbers: sessions with p < 0.05 (smallest possible p 0.001)", transform=ax.transAxes, ha="right", fontsize=8.8, color=SOFT)
    for ext in ("png", "pdf"):
        fig.savefig(ROOT / "figures" / f"subspace_hc11.{ext}", dpi=200)
    plt.close(fig)


def main(argv):
    workers = next((int(a.split("=", 1)[1]) for a in argv if a.startswith("--workers=")), os.cpu_count() or 2)
    for v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "VECLIB_MAXIMUM_THREADS"):
        os.environ.setdefault(v, "1")
    todo = [(n, e) for n in HC11_ORDER for e in ("post", "pre") if not (OUT / f"{n}_{e}.pkl").exists()]
    with ProcessPoolExecutor(max_workers=workers) as pool:
        for name, epoch, s in pool.map(job, *zip(*todo)) if todo else []:
            print(name, epoch, s, flush=True)
    R = summary()
    figure(R)
    print((OUT / "summary.md").read_text())


if __name__ == "__main__":
    main(sys.argv[1:])
