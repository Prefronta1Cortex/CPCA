"""Check the new comparison methods on planted data before using them on hc-11.

Count PCA/ICA assemblies (baselines/count_assemblies.py), SPOTDisClust (baselines/spotdis_baseline.py) and
Rastermap (baselines/rastermap_baseline.py), with complex PCA as the reference, on 1500 planted events of
80 cells: D (two routes on different cells, forward), L0 (one map, both directions), L2 (two maps on the same
cells, both directions), and a control without replays; 3 draws each. Per planted map: the order test (best
output, best-of-outputs null) and the compactness test (members' fields close together, best-of-outputs null).

Usage: python scripts/validate_methods.py [--workers=10]
Output: results/methods_hc11/validation.md
"""

import os
import pickle
import sys
import time
import zlib
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "results" / "methods_hc11"
CONDITIONS = {"D two routes, different cells": ("D", dict(replay_frac=0.4, reverse_frac=0.0, participation=0.15), dict(n_routes=2)),
              "L0 one map, both directions": ("L0", dict(replay_frac=0.4, reverse_frac=0.5, participation=0.15, jitter_ms=8.0), dict(n_routes=1, cells_per_route=60)),
              "L2 two maps, same cells": ("L2", dict(replay_frac=0.4, reverse_frac=0.5, participation=0.15, jitter_ms=8.0),
                                          dict(n_routes=1, cells_per_route=60, direction_maps=True)),
              "no replays": ("none", dict(replay_frac=0.0, participation=0.15), dict(n_routes=1, cells_per_route=60))}
METHODS = ["cpca", "count_ica", "spotdis", "rastermap"]


def seed(*parts):
    return zlib.crc32("|".join(map(str, parts)).encode())


def outputs(method, times, T, rng):
    """(orders, member sets) of a method on events."""
    from cpca import fit
    from cpca.direction import order_of
    if method == "cpca":
        res = fit(times, T, rng=rng, ica=False, n_shuffles=50)
        orders = [order_of(res["pca_components"][:, j]) for j in range(res["n_kept"])]
        return orders, [np.isfinite(o) for o in orders]
    if method == "count_ica":
        from baselines import count_assemblies
        r = count_assemblies.fit(times, T, rng)
        return [], r["members"]
    if method == "spotdis":
        from baselines import spotdis_baseline
        r = spotdis_baseline.fit(times, T, rng)
        return r["orders"], r["members"]
    if method == "rastermap":
        from baselines import rastermap_baseline
        r = rastermap_baseline.fit(times, T, rng)
        return r["orders"], []


def job(cond, draw):
    from cpca.evaluate import best_compactness
    from scripts.plot_hc11_sequences import best_map_match
    from sim.routes import generate, make_routes
    code, gk, rk = CONDITIONS[cond]
    rng = np.random.default_rng(seed("validate-methods", cond, draw))
    data = generate(rng, n_cells=80, n_events=1500, routes=make_routes(rng, n_cells=80, **rk), **gk)
    T = np.full(data["times"].shape[0], data["event_ms"])
    row = {"condition": cond, "draw": draw, "methods": {}}
    for m in METHODS:
        t0 = time.perf_counter()
        orders, sets = outputs(m, data["times"], T, rng)
        res = {"runtime_s": time.perf_counter() - t0, "n_orders": len(orders), "n_sets": len(sets), "maps": []}
        for cen in data["centres"]:
            key = {1.0: cen * 100}
            res["maps"].append({"order": best_map_match(orders, key, False, 100.0, rng, n_null=500) if orders else None,
                                "compact": best_compactness(sets, key, False, 100.0, rng) if sets else None})
        row["methods"][m] = res
    return row


def main(argv):
    workers = next((int(a.split("=", 1)[1]) for a in argv if a.startswith("--workers=")), os.cpu_count() or 2)
    for v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "VECLIB_MAXIMUM_THREADS", "NUMBA_NUM_THREADS"):
        os.environ[v] = "1"
    jobs = [(c, d) for c in CONDITIONS for d in range(3)]
    with ProcessPoolExecutor(max_workers=workers) as pool:
        rows = list(pool.map(job, *zip(*jobs)))
    OUT.mkdir(parents=True, exist_ok=True)
    pickle.dump(rows, open(OUT / "validation.pkl", "wb"))
    lines = ["# Comparison methods on planted data", "", "Generated by `scripts/validate_methods.py`. 1500 events, 80 cells, 3 draws per condition. "
             "Per planted map: order test (|ρ| of the best output, share of maps with p < 0.05) and compactness test (share with p < 0.05; "
             "mean field distance of the best output's members over the null mean). '–': the method returns no output of that kind (no components, clusters or orders), so there is nothing to test; on the control without replays this is the correct answer.", "",
             "| condition | " + " | ".join(f"{m}: order" for m in METHODS) + " | " + " | ".join(f"{m}: compact" for m in METHODS) + " | " +
             " | ".join(f"{m}: s" for m in METHODS) + " |", "|---" * (1 + 3 * len(METHODS)) + "|"]
    for cond in CONDITIONS:
        rs = [r for r in rows if r["condition"] == cond]
        oc, cc, tc = [], [], []
        for m in METHODS:
            maps = [mp for r in rs for mp in r["methods"][m]["maps"]]
            o = [mp["order"] for mp in maps if mp["order"] is not None]
            c = [mp["compact"] for mp in maps if mp["compact"] is not None]
            oc.append(f"{np.mean([x['p'] < 0.05 if np.isfinite(x['p']) else False for x in o]):.0%}, |ρ| {np.nanmedian([x['abs'] for x in o]):.2f}" if o else "–")
            cc.append(f"{np.mean([x['p'] < 0.05 if np.isfinite(x['p']) else False for x in c]):.0%}, ratio {np.nanmedian([x['ratio'] for x in c]):.2f}" if c else "–")
            tc.append(f"{np.median([r['methods'][m]['runtime_s'] for r in rs]):.1f}")
        lines.append(f"| {cond} | " + " | ".join(oc) + " | " + " | ".join(cc) + " | " + " | ".join(tc) + " |")
    (OUT / "validation.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1:])
